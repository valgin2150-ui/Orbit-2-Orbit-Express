export function getCompaniesByCountry(): Record<string, SpaceCompany[]> {
  const byCountry: Record<string, SpaceCompany[]> = {};
  spaceCompanies.forEach(company => {
    if (!byCountry[company.country]) {
      byCountry[company.country] = [];
    }
    byCountry[company.country].push(company);
  });
  Object.keys(byCountry).forEach(country => {
    byCountry[country].sort((a, b) => a.name.localeCompare(b.name));
  });
  return byCountry;
}

export function getCompaniesBySegment(): Record<string, SpaceCompany[]> {
  const bySegment: Record<string, SpaceCompany[]> = {};
  spaceCompanies.forEach(company => {
    company.segments.forEach(segment => {
      if (!bySegment[segment]) {
        bySegment[segment] = [];
      }
      bySegment[segment].push(company);
    });
  });
  Object.keys(bySegment).forEach(segment => {
    bySegment[segment].sort((a, b) => a.name.localeCompare(b.name));
  });
  return bySegment;
}

export function getCountryStats(): { country: string; countryCode: string; count: number }[] {
  const stats: Record<string, { country: string; countryCode: string; count: number }> = {};
  spaceCompanies.forEach(company => {
    if (!stats[company.country]) {
      stats[company.country] = { country: company.country, countryCode: company.countryCode, count: 0 };
    }
    stats[company.country].count++;
  });
  return Object.values(stats).sort((a, b) => b.count - a.count);
}

