export function extractUSState(headquartersCity: string): string | null {
  if (headquartersCity === "Washington, D.C.") return "DC";
  const parts = headquartersCity.split(", ");
  if (parts.length < 2) return null;
  const code = parts[parts.length - 1].trim();
  if (/^[A-Z]{2}$/.test(code) && US_STATE_NAMES[code]) return code;
  return null;
}

export function searchCompanies(query: string): SpaceCompany[] {
  const lowerQuery = query.toLowerCase();
  return spaceCompanies.filter(company => {
    if (
      company.name.toLowerCase().includes(lowerQuery) ||
      company.country.toLowerCase().includes(lowerQuery) ||
      company.headquartersCity.toLowerCase().includes(lowerQuery) ||
      company.description.toLowerCase().includes(lowerQuery) ||
      company.segments.some(s => s.toLowerCase().includes(lowerQuery))
    ) return true;
    if (company.countryCode === "US") {
      const stateCode = extractUSState(company.headquartersCity);
      if (stateCode) {
        const stateName = US_STATE_NAMES[stateCode] ?? "";
        if (
          stateCode.toLowerCase() === lowerQuery ||
          stateName.toLowerCase().includes(lowerQuery)
        ) return true;
      }
    }
    return false;
  });
}

export function getCompanyById(id: string): SpaceCompany | undefined {
  return spaceCompanies.find(company => company.id === id);
}
